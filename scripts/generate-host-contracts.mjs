import {execFileSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const schemas=JSON.parse(execFileSync('cargo',['run','--quiet','-p','vibeone-workbench','--example','export_contracts'],{cwd:root,encoding:'utf8',maxBuffer:4*1024*1024}));
const definitions=new Map();
for(const schema of Object.values(schemas))for(const [name,value] of Object.entries(schema.definitions??{})){
 if(definitions.has(name)&&JSON.stringify(definitions.get(name))!==JSON.stringify(value))throw Error(`Conflicting schema: ${name}`);
 definitions.set(name,value);
}
const identifier=name=>{if(!/^[A-Za-z_]\w*$/.test(name))throw Error(`Unsupported type name: ${name}`);return name;};
function type(schema){
 if(schema===false)return 'never';
 if(schema===true||Object.keys(schema).every(key=>['title','description','default','examples','deprecated','readOnly','writeOnly','$schema','$id','definitions'].includes(key)))return 'JsonValue';
 if(schema.$ref){const name=schema.$ref.replace(/^#\/definitions\//,'');return identifier(name);}
 if(schema.enum)return schema.enum.map(value=>JSON.stringify(value)).join(' | ');
 if(schema.anyOf||schema.oneOf)return (schema.anyOf??schema.oneOf).map(item=>`(${type(item)})`).join(' | ');
 if(schema.allOf)return schema.allOf.map(item=>`(${type(item)})`).join(' & ');
 if(Array.isArray(schema.type))return schema.type.map(value=>type({...schema,type:value})).join(' | ');
 switch(schema.type){
  case 'string':return 'string';case 'integer':case 'number':return 'number';case 'boolean':return 'boolean';case 'null':return 'null';
  case 'array':if(Array.isArray(schema.items))throw Error('Tuple schema requires an explicit exporter');return `Array<${type(schema.items??{})}>`;
  case 'object':{
   const required=new Set(schema.required??[]);
   const properties=Object.entries(schema.properties??{}).map(([key,value])=>`${JSON.stringify(key)}${required.has(key)?'':'?'}: ${type(value)};`);
   if(schema.additionalProperties===true||schema.additionalProperties&&typeof schema.additionalProperties==='object'){
    const extra=schema.additionalProperties===true?'JsonValue':type(schema.additionalProperties);
    const optional=Object.keys(schema.properties??{}).some(key=>!required.has(key));
    properties.push(`[key: string]: ${extra}${optional?' | undefined':''};`);
   }
   return `{ ${properties.join(' ')} }`;
  }
  default:throw Error(`Unsupported schema: ${JSON.stringify(schema)}`);
 }
}
const header='// Generated by npm run contracts:generate from actual Rust HTTP types. Do not edit.\n';
const entries=new Map([...definitions,...Object.entries(schemas)]);
const source=header+'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n'+[...entries].sort(([a],[b])=>a<b?-1:a>b?1:0).map(([name,schema])=>`export type ${identifier(name)} = ${type(schema)};`).join('\n')+'\n';
for(const [path,value] of [['packages/client-contracts/src/generated.ts',source],['packages/client-contracts/schemas.json',JSON.stringify(schemas,null,2)+'\n']]){
 const file=root+path;
 if(process.argv.includes('--check')){if(await readFile(file,'utf8').catch(()=>null)!==value)throw Error(`Stale contract: ${path}; run npm run contracts:generate`);}
 else await writeFile(file,value);
}
console.log(process.argv.includes('--check')?'Host contracts match Rust sources':'Generated Host contracts');
