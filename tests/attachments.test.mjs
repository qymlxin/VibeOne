import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import {host} from './helpers/host.mjs';
const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aD1sAAAAASUVORK5CYII=','base64');
test('uploaded content is scoped, deduplicated, passed as real ACP blocks and retained by history',{timeout:20000},async t=>{
 const {directory,call,wait}=await host(t);
 const {id}=await call('/sessions',{provider:'demo',workspace:directory});
 const other=await call('/sessions',{provider:'demo',workspace:directory});
 const image=await call(`/sessions/${id}/attachments`,{name:'../photo.png',mimeType:'image/png',data:png.toString('base64')});
 assert.equal(image.name,'photo.png');assert.equal(image.kind,'image');assert.equal(image.size,png.length);
 const duplicate=await call(`/sessions/${id}/attachments`,{name:'photo.png',mimeType:'image/png',data:png.toString('base64')});assert.equal(image.id,duplicate.id);
 assert.equal((await call(`/sessions/${id}/attachments/${image.id}`)).data,png.toString('base64'));
 await call(`/sessions/${other.id}/attachments/${image.id}`,undefined,false);
 await call(`/sessions/${other.id}/messages`,{text:'forbidden attachment',attachments:[image.id]},false);
 await call(`/sessions/${id}/messages`,{text:'too many',attachments:Array(6).fill(image.id)},false);
 await call(`/sessions/${id}/messages`,{text:'duplicate attachment',attachments:[image.id,image.id]},false);
 const request={text:'请查看图片',key:'image-once',attachments:[image.id]};
 const accepted=await call(`/sessions/${id}/messages`,request);
 const done=await wait(id,session=>session.runs.find(run=>run.id===accepted.operationId)?.status==='completed');
 assert.ok(done.messages.some(message=>message.role==='assistant'&&message.text.includes(`image ${png.length} ${createHash('sha256').update(png).digest('hex')}`)));
 assert.equal(done.messages.find(message=>message.role==='user').attachments[0].id,image.id);
 assert.equal((await call(`/sessions/${id}/messages`,request)).duplicate,true);
 await call(`/sessions/${id}/messages`,{...request,attachments:[]},false);
 assert.equal((await call(`/sessions/${id}/attachments/${image.id}/remove`,{})).retainedForHistory,true);
 const bytes=Buffer.alloc(300_000,7);
 const binary=await call(`/sessions/${id}/attachments`,{name:'context.bin',mimeType:'application/octet-stream',data:bytes.toString('base64')});
 const sent=await call(`/sessions/${id}/messages`,{text:'',attachments:[binary.id]});
 const got=await wait(id,session=>session.runs.find(run=>run.id===sent.operationId)?.status==='completed');
 assert.ok(got.messages.some(message=>message.text.includes(`resource ${bytes.length} ${createHash('sha256').update(bytes).digest('hex')}`)));
 const draft=await call(`/sessions/${id}/attachments`,{name:'note.txt',mimeType:'text/plain',data:Buffer.from('上传文本').toString('base64')});
 assert.equal(draft.kind,'text');await call(`/sessions/${id}/attachments/${draft.id}/remove`,{});await call(`/sessions/${id}/attachments/${draft.id}`,undefined,false);
 await call(`/sessions/${id}/attachments`,{name:'fake.png',mimeType:'image/png',data:'dGV4dA=='},false);
 await call(`/sessions/${id}/attachments`,{name:'big.bin',mimeType:'application/octet-stream',data:Buffer.alloc(4*1024*1024+1).toString('base64')},false);
 const profile=await call('/profiles',{name:'no media',provider:'demo',args:[join(directory,'demo-agent.mjs'),'--no-media']});
 const noMedia=await call('/sessions',{provider:'demo',workspace:directory,profileId:profile.id});
 const unsupported=await call(`/sessions/${noMedia.id}/attachments`,{name:'photo.png',mimeType:'image/png',data:png.toString('base64')});
 await call(`/sessions/${noMedia.id}/messages`,{text:'图片能力未知',attachments:[unsupported.id]});
 const failed=await wait(noMedia.id,session=>session.status==='error');assert.match(failed.error,/未声明图片能力/);
 await call(`/sessions/${noMedia.id}/messages`,{text:'known unsupported',attachments:[unsupported.id]},false);
 const plain=await call(`/sessions/${noMedia.id}/attachments`,{name:'plain.txt',mimeType:'text/plain',data:Buffer.from('无媒体能力仍能接收文本附件').toString('base64')});
 const textRun=await call(`/sessions/${noMedia.id}/messages`,{text:'',attachments:[plain.id]});
 const textDone=await wait(noMedia.id,session=>session.runs.find(run=>run.id===textRun.operationId)?.status==='completed');
 assert.ok(textDone.messages.some(message=>message.role==='assistant'&&message.text.includes('无媒体能力仍能接收文本附件')));
});
